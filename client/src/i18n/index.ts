export type Locale = keyof typeof catalogs;
export type MessageKey = keyof typeof catalogs.en;

export const LOCALES: Locale[] = ["en", "he", "es", "ru", "ar"];

export const LOCALE_LABEL: Record<Locale, string> = {
  en: "English",
  he: "עברית",
  es: "Español",
  ru: "Русский",
  ar: "العربية",
};

let chosen: Locale = "en";
const listeners = new Set<() => void>();

export function locale(): Locale {
  return chosen;
}

export function subscribeLocale(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export async function loadLocale() {
  chosen = "en";
}

export async function setLocale(next: Locale) {
  chosen = next;
  listeners.forEach((listener) => listener());
  try {
    const { default: AsyncStorage } = await import("@react-native-async-storage/async-storage");
    await AsyncStorage.setItem("shulchan.locale", next);
  } catch {
    // The choice still applies for this run.
  }
}

const rtl = new Set<Locale>(["he", "ar"]);

export function isRtl() {
  return rtl.has(locale());
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const template = catalogs[locale()][key] ?? catalogs.en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}
