  const fonts = {
    he: "https://fonts.googleapis.com/css2?family=Rubik:wght@400;500;600;700;800&display=swap",
    ar: "https://fonts.googleapis.com/css2?family=Cairo:wght@400;500;600;700;800&display=swap",
  };

  let current = LOCALES.includes(window.__loochkaLocale) ? window.__loochkaLocale : "en";

  function t(key) {
    const table = catalogs[current] || catalogs.en;
    const value = table[key];
    return value == null || value === "" ? (catalogs.en[key] ?? key) : value;
  }

  function ensureFont(lang) {
    const href = fonts[lang];
    if (!href || document.querySelector(`link[data-locale-font="${lang}"]`)) return;
    const link = document.createElement("link");
    link.rel = "stylesheet";
    link.href = href;
    link.setAttribute("data-locale-font", lang);
    document.head.appendChild(link);
  }

  function apply(lang) {
    current = LOCALES.includes(lang) ? lang : "en";
    document.documentElement.lang = current;
    document.documentElement.dir = RTL.has(current) ? "rtl" : "ltr";
    for (const el of document.querySelectorAll("[data-i18n]")) {
      el.textContent = t(el.getAttribute("data-i18n"));
    }
    for (const el of document.querySelectorAll("[data-i18n-html]")) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    }
    for (const el of document.querySelectorAll("[data-i18n-aria]")) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    }
    for (const el of document.querySelectorAll("[data-i18n-alt]")) {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    }
    for (const el of document.querySelectorAll("meta[data-i18n-content]")) {
      el.setAttribute("content", t(el.getAttribute("data-i18n-content")));
    }
    const code = document.querySelector("[data-lang-current]");
    if (code) code.textContent = current.toUpperCase();
    for (const button of document.querySelectorAll(".lang-menu [data-lang]")) {
      const on = button.getAttribute("data-lang") === current;
      button.setAttribute("aria-selected", String(on));
    }
    document.documentElement.classList.remove("i18n-pending");
    document.dispatchEvent(new CustomEvent("loochka:locale"));
  }

  function setLocale(lang) {
    if (!LOCALES.includes(lang)) return;
    try { localStorage.setItem(STORAGE, lang); } catch { /* the choice still applies for this page */ }
    window.__loochkaLocale = lang;
    const url = new URL(location.href);
    if (url.searchParams.has("lang")) {
      url.searchParams.delete("lang");
      history.replaceState(null, "", `${url.pathname}${url.search}${url.hash}`);
    }
    ensureFont(lang);
    apply(lang);
  }

  ensureFont(current);
  apply(current);
  window.loochkaI18n = { t, setLocale, locale: () => current, locales: LOCALES };
